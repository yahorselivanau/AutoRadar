import type { SearchIntentMode } from "@autoradar/domain";

export type IntentGoldenCase = {
  id: string;
  text: string;
  expectedMode: SearchIntentMode;
};

function cases(
  prefix: string,
  expectedMode: SearchIntentMode,
  texts: readonly string[],
): IntentGoldenCase[] {
  return texts.map((text, index) => ({
    id: `${prefix}-${String(index + 1).padStart(2, "0")}`,
    text,
    expectedMode,
  }));
}

